    __HAL_RCC_GPIOA_CLK_ENABLE();
    /**SPI1 GPIO Configuration
    PA5     ------> SPI1_SCK
    PA6     ------> SPI1_MISO
    PA7     ------> SPI1_MOSI
    */
    /* W25Q128 外置 Flash 走 SPI1，引脚必须和 bootloader 的 bootloaer.ioc 完全一致，
     * 否则应用能读写、bootloader 却读不到同一颗 Flash。SPI1 在 APB2 上，速率比 SPI2 高。
     * 【MISO(PA6) 绝不能配成 AF_PP】它是"从片 → 主机"的方向，主机在这条线上只做输入；
     * 配成推挽输出就和 W25Q 的 SO 顶牛（两个推挽对推），读回来的数据、
     * 甚至那颗芯片的输出级都保不齐。bootloader 侧就是把 PA6 单独配 INPUT 的。 */
